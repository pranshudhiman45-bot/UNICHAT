import { test, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
const root = process.cwd();
async function codeFor(email: string, subject: string) {
  const directory = path.join(root, '.local/mail');
  for (const filename of (await fs.readdir(directory)).sort().reverse()) {
    const mail = JSON.parse(await fs.readFile(path.join(directory, filename), 'utf8'));
    if (mail.to === email && mail.subject.includes(subject)) return mail.text.match(/\b\d{6}\b/)[0];
  }
  throw new Error('Test email not found');
}
test('registration → workspace → message → refresh → password recovery', async ({ page, browser }) => {
  const errors: string[] = []; page.on('pageerror', (error) => errors.push(error.message));
  const id = Date.now().toString();
  const email = `browser${id}@example.test`;
  const password = 'Browser test passphrase 2026!';
  await page.goto('/register');
  await page.getByLabel('Full name').fill('Browser Tester');
  await page.getByLabel('Username', { exact: true }).fill(`browser${id}`);
  await page.getByLabel('Email address').fill(email);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Create your account', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Check your inbox.' })).toBeVisible();
  await page.getByLabel('Verification code', { exact: true }).fill(await codeFor(email, 'Verify'));
  await page.getByRole('button', { name: 'Verify and continue' }).click();
  await expect(page).toHaveURL(/\/workspaces/);
  await page.getByRole('button', { name: 'Create workspace', exact: true }).click();
  await page.getByLabel('Workspace name').fill(`Browser Team ${id}`);
  await page.getByRole('button', { name: 'Create', exact: true }).click();
  await expect(page).toHaveURL(/\/chat\//);
  await expect(page.locator('[contenteditable="true"]')).toBeVisible();
  await page.locator('[contenteditable="true"]').fill('Hello from the browser regression test.');
  await page.locator('[contenteditable="true"]').press('Enter');
  await expect(page.getByText('Hello from the browser regression test.', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText('Hello from the browser regression test.', { exact: true })).toBeVisible();
  const otherTab = await page.context().newPage();
  await Promise.all([page.reload(), otherTab.goto('/workspaces')]);
  await expect(otherTab.getByRole('heading', { name: 'Your workspaces' })).toBeVisible();
  await expect(page.getByText('Hello from the browser regression test.', { exact: true })).toBeVisible();
  await otherTab.close();
  const recoveryContext = await browser.newContext({ baseURL: 'http://localhost:5173' });
  const recovery = await recoveryContext.newPage();
  await recovery.goto('/forgot-password');
  await recovery.getByLabel('Account email').fill(email);
  await recovery.getByRole('button', { name: 'Send recovery code' }).click();
  await expect(recovery.getByLabel('Six-digit recovery code')).toBeVisible();
  await recovery.getByLabel('Six-digit recovery code').fill(await codeFor(email, 'Reset'));
  await recovery.getByRole('button', { name: 'Verify code', exact: true }).click();
  await recovery.getByLabel('New password', { exact: true }).fill('Another test passphrase 2026!');
  await recovery.getByLabel('Confirm new password', { exact: true }).fill('Another test passphrase 2026!');
  await recovery.getByRole('button', { name: 'Update password' }).click();
  await expect(recovery.getByText('Password updated. All existing sessions have been signed out.')).toBeVisible();
  await page.reload();
  await expect(page).toHaveURL(/\/login/);
  await recovery.getByRole('link', { name: 'Back to sign in' }).click();
  await recovery.getByLabel('Email address').fill(email);
  await recovery.getByLabel('Password', { exact: true }).fill('Another test passphrase 2026!');
  await recovery.getByRole('button', { name: 'Sign in to Unichat' }).click();
  await expect(recovery).toHaveURL(/\/workspaces/);
  await recoveryContext.close();
  expect(errors).toEqual([]);
});

test('demo chat, emoji, responsive layout, and appearance', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', (error) => errors.push(error.message));
  const accounts = JSON.parse(await fs.readFile(path.join(root, '.local/test-accounts.json'), 'utf8'));
  await page.goto('/login');
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible();
  await fs.mkdir(path.join(root, '.local/qa'), { recursive: true });
  await page.screenshot({ path: '.local/qa/login-desktop.png', fullPage: true });
  await page.getByLabel('Email address').fill(accounts.alex.email);
  await page.getByLabel('Password', { exact: true }).fill(accounts.alex.password);
  await page.getByRole('button', { name: 'Sign in to Unichat' }).click();
  await page.getByRole('button', { name: /Northstar Studio/ }).click();
  await page.getByRole('button', { name: /^general(?: |$)/ }).click();
  await expect(page.getByText('Welcome to Northstar Studio!', { exact: false })).toBeVisible();
  await page.screenshot({ path: '.local/qa/chat-desktop.png', fullPage: true });
  let release!: () => void;
  let finished!: () => void;
  let intercepted = false;
  const gate = new Promise<void>((resolve) => { release = resolve; });
  const done = new Promise<void>((resolve) => { finished = resolve; });
  await page.route('**/api/messages/channel/*', async (route) => {
    if (intercepted) return route.continue();
    intercepted = true;
    const response = await route.fetch();
    await gate;
    await route.fulfill({ response });
    finished();
  });
  await page.getByRole('button', { name: 'design', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'design', exact: true })).toBeVisible();
  await page.getByRole('button', { name: /^general(?: |$)/ }).click();
  await expect(page.getByText('Welcome to Northstar Studio!', { exact: false })).toBeVisible();
  release(); await done;
  await expect(page.getByText('Welcome to Northstar Studio!', { exact: false })).toBeVisible();
  await page.unroute('**/api/messages/channel/*');
  await page.getByRole('button', { name: 'Insert emoji', exact: true }).click();
  await expect(page.locator('em-emoji-picker')).toBeVisible();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Account and appearance' }).click();
  await page.getByRole('combobox').selectOption('dark');
  await page.keyboard.press('Escape');
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await expect(page.getByRole('region', { name: 'Messages', exact: true }).locator(':scope > div').first()).toHaveCSS('background-color', 'rgb(24, 19, 25)');
  await page.screenshot({ path: '.local/qa/chat-dark.png', fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('button', { name: 'Toggle workspace sidebar' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await expect(page.locator('#workspace-sidebar')).toHaveAttribute('aria-hidden', 'true');
  await page.screenshot({ path: '.local/qa/chat-mobile.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Toggle workspace sidebar' }).click();
  await expect(page.getByRole('complementary', { name: 'Workspace sidebar' })).toBeVisible();
  expect(errors).toEqual([]);
});
